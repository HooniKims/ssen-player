"""Keep installer candidates in sync with portable app registration."""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))
from app.file_associations import registration_entries, CAPABILITIES, PROG_ID


def render():
    lines = ['; Generated by scripts/render_associations.py', '[Registry]']
    for path, name, value in registration_entries(r'{app}\SsenPlayer.exe'):
        escape = lambda text: text.replace('"', '""')
        flags = 'uninsdeletevalue'
        if path in ('Software\\Classes\\' + PROG_ID, CAPABILITIES):
            flags = 'uninsdeletekey'
        lines.append(f'Root: HKCU; Subkey: "{escape(path)}"; ValueType: string; '
                     f'ValueName: "{escape(name)}"; ValueData: "{escape(value)}"; Flags: {flags}')
    return '\n'.join(lines) + '\n'


if __name__ == '__main__':
    (ROOT / 'build/associations.iss').write_text(render(), 'utf-8-sig')
